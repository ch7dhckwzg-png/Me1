#!/usr/bin/env bash
# Trace assets/catalyze-logo-white.png into assets/catalyze-logo.svg and src/logo/logoPath.ts.
# Needs ImageMagick (convert) and potrace.
set -euo pipefail
cd "$(dirname "$0")/.."
tmp=$(mktemp -d)
# Crop to the mark (10 px padding), upscale 2x so the halftone dots trace cleanly, threshold.
convert assets/catalyze-logo-white.png -colorspace gray -crop 1286x488+367+719 +repage \
  -filter Lanczos -resize 200% -threshold 50% -negate "$tmp/logo.pbm"
potrace "$tmp/logo.pbm" -s -t 4 -a 1.0 -O 0.4 --flat -o "$tmp/raw.svg"
python3 - "$tmp/raw.svg" <<'PY'
import re, sys
s = open(sys.argv[1]).read()
g = re.search(r'<g transform="([^"]+)"[^>]*>(.*?)</g>', s, re.S)
d = ' '.join(p.replace('\n', ' ') for p in re.findall(r'd="([^"]+)"', g.group(2)))
t = g.group(1)
open('assets/catalyze-logo.svg', 'w').write(
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 2572 976" fill="currentColor">\n'
    f'<title>CATALYZE</title>\n<g transform="{t}"><path d="{d}"/></g>\n</svg>\n')
open('src/logo/logoPath.ts', 'w').write(
    '// Generated by scripts/trace-logo.sh from assets/catalyze-logo-white.png. Do not edit.\n'
    'export const LOGO_VIEWBOX = { width: 2572, height: 976 };\n'
    f'export const LOGO_TRANSFORM = "{t}";\n'
    f'export const LOGO_PATH = "{d}";\n')
PY
cp assets/catalyze-logo.svg public/catalyze-logo.svg
rm -rf "$tmp"
echo "Wrote assets/catalyze-logo.svg and src/logo/logoPath.ts"
